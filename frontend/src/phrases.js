export const PHRASES = {
  welcome: [
    'Добро пожаловать в Удивительный Цифровой Цирк! Я ваш конферансье!',
    'О, походу у нас новенький!',
  ],
  finished: [
    'Готово! Заходите, не стесняйтесь!',
    'У меня отлично получается!',
    'Вход там, внизу. Сундук я спрятал подальше.',
  ],
  thinking: [
    'Это лишь головоломка которую надо решить!',
    'Так, где я оставил тот коридор...',
    'Ещё пара стен и будет красиво.',
  ],
  invent: [
    'О! А если так соединить...',
    'Я придумал новую штуку, надо попробовать!',
    'Такого я ещё не строил.',
    'Запомню это на следующую постройку.',
    'Кажется, я только что изобрёл что-то полезное.',
  ],
  miss: [
    'Ой. Этот кубик сюда не подходит...',
    'Ладно, ладно, я просто пробую!',
  ],
}

// Фразы перебираются по кругу, а не случайно: выбор должен быть
// детерминированным (иначе это побочный эффект в рендере) и без повторов подряд.
const cursors = {}

export function nextPhrase(event) {
  const list = PHRASES[event]
  if (!list || list.length === 0) return null
  const i = cursors[event] ?? 0
  cursors[event] = (i + 1) % list.length
  return list[i]
}
