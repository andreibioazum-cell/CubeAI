# Модули, написанные вручную. Их Кейн не изобретал — это физика словаря,
# и она не вымирает. Всё, что он придумает сам, добавляется поверх.
BASE_MODULE_NAMES = set(MODULES)

VARIANTS = {}


def _build_variants(name):
    """Все повороты модуля и их гнёзда."""
    out, seen = [], set()
    for k in range(4):
        g = rotate(MODULES[name]['grid'], k)
        key = g.tobytes()
        if key in seen:
            continue          # симметричные повороты не дублируем
        seen.add(key)
        out.append({'rot': k, 'grid': g, 'sockets': sockets(g)})
    return out


def register_module(name, grid, role='room', decor=(), height=1.0):
    """Добавить модуль в словарь на ходу."""
    MODULES[name] = {'grid': np.asarray(grid, dtype=np.int8).tolist(),
                     'role': role, 'decor': list(decor), 'height': float(height)}
    VARIANTS[name] = _build_variants(name)
    return name


def unregister_module(name):
    if name in BASE_MODULE_NAMES:
        return False
    MODULES.pop(name, None)
    VARIANTS.pop(name, None)
    return True


for _name in list(MODULES):
    VARIANTS[_name] = _build_variants(_name)


def variants_with_socket(name, side):
    """Повороты модуля, у которых есть гнездо на указанной стороне."""
    return [v for v in VARIANTS[name] if side in v['sockets']]


def rotate_cell(r, c, k):
    """Куда уезжает клетка (r, c) после поворота на k*90° (как в np.rot90)."""
    for _ in range(k % 4):
        r, c = TILE - 1 - c, r
    return r, c
