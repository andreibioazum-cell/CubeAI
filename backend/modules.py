"""Словарь Кейна: осмысленные модули вместо отдельных кубиков."""

import numpy as np

TILE = 6

# Стороны и смещения в координатах тайлов (ty растёт на юг)
SIDES = ('N', 'E', 'S', 'W')
DELTA = {'N': (0, -1), 'E': (1, 0), 'S': (0, 1), 'W': (-1, 0)}
OPPOSITE = {'N': 'S', 'S': 'N', 'E': 'W', 'W': 'E'}


def _edge(grid, side):
    """Клетки на указанной границе тайла."""
    g = np.asarray(grid)
    if side == 'N': return g[0, :]
    if side == 'S': return g[TILE - 1, :]
    if side == 'W': return g[:, 0]
    return g[:, TILE - 1]


def sockets(grid):
    """Стороны, на которых есть проход наружу."""
    return {s for s in SIDES if np.any(_edge(grid, s) == 0)}


def rotate(grid, k):
    """Поворот на k*90°. Гнёзда пересчитываются из повёрнутой сетки,"""
    return np.rot90(np.asarray(grid), k).copy()


